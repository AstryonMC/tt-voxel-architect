"""Compile architectural expressions and palette strings to synthesizable case ROMs."""
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from model.architect import PROGRAMS, ROLES, PALETTES, FIXED
ROOT=Path(__file__).resolve().parents[1]

def generate():
    roles=ROLES+['texture']
    lines=['// Generated by tools/compile_rom.py; edit model/architect.py instead.',
           'function [9:0] expression; input [9:0] address; input [2:0] bound_index; begin case (address)']
    starts=[];ends=[];pc=0
    rolelines=[]
    for program in PROGRAMS:
        starts.append(pc)
        for coords,r in program:
            lines.append(f"10'd{pc}: case(bound_index)")
            for i,v in enumerate(coords): lines.append(f"3'd{i}: expression=10'd{(v.k<<6)|(v.off&63)};")
            lines.append('default: expression=0; endcase')
            rolelines.append(f"10'd{pc}: role=6'd{roles.index(r)};")
            pc+=1
        ends.append(pc)
    lines += ["default: expression=0; endcase end endfunction",'function [5:0] role; input [9:0] address; begin case(address)']+rolelines+['default: role=0; endcase end endfunction']
    for name,values in [('first_pc',starts),('last_pc',ends)]:
        lines += [f'function [9:0] {name}; input [2:0] a; begin case(a)']+[f"3'd{i}: {name}=10'd{v};" for i,v in enumerate(values)]+[f'default: {name}=0; endcase end endfunction']
    names=list(dict.fromkeys([s for p in PALETTES for s in p]+FIXED))
    lines+=['function [6:0] block_id; input [5:0] r; input [1:0] p; input [1:0] noise; begin case({p,r})']
    for p in range(4):
        for r,name in enumerate(roles):
            if name=='texture':
                ids=[names.index(s) for s in ['mossy_stone_bricks','cracked_stone_bricks','stone_bricks','cobblestone']] if p==0 else [names.index(PALETTES[p][0])]*4
                lines.append(f"8'd{p*64+r}: case(noise) "+' '.join(f"2'd{i}: block_id=7'd{n};" for i,n in enumerate(ids))+' endcase')
            else: lines.append(f"8'd{p*64+r}: block_id=7'd{names.index(PALETTES[p][r] if r<13 else name)};")
    lines+=['default: block_id=0; endcase end endfunction','function [7:0] name_char; input [6:0] id; input [5:0] offset; begin case(id)']
    for i,s in enumerate(names):
        lines.append(f"7'd{i}: case(offset)")
        for j,ch in enumerate(s):lines.append(f"6'd{j}: name_char=8'd{ord(ch)};")
        lines.append('default: name_char=0; endcase')
    lines+=['default: name_char=0; endcase end endfunction']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    target=ROOT/'src/rom.vh'
    if '--check' in sys.argv: assert target.read_text()==generate(), 'ROM stale'
    else: target.write_text(generate())
